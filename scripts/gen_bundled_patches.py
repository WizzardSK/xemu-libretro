#!/usr/bin/env python3
"""Writes ui/libretro-bundled-patches.h, the patches bundled with the core:
the 16-9 Widescreen, 60 FPS and Miscellaneous folders of
icup321/XboxGraphicalPatches, and the 16:9 database of the OgXHD tool in it
(!OgXHD/wdb.dat), with its maintainer's permission
(https://github.com/icup321/XboxGraphicalPatches/issues/16).

wdb.dat lists, per title ID, lines of bytes to find, each followed by the
bytes to put in their place; OgXHD replaces every place they are found. Each
title becomes a patch "<game> (16-9 Widescreen, OgXHD).wdb" holding those
lines, listed for that title ID (ui/libretro.c, xbe_apply_wdb).

    python3 scripts/gen_bundled_patches.py <XboxGraphicalPatches checkout> [commit]
"""
import os
import sys

FOLDERS = ["16-9 Widescreen Patches", "60 FPS Patches", "Miscellaneous Patches"]

src = sys.argv[1]
commit = sys.argv[2] if len(sys.argv) > 2 else "?"
files = []
for folder in FOLDERS:
    for name in sorted(os.listdir(os.path.join(src, folder))):
        if name.lower().endswith((".ips", ".bps", ".jmp")):
            files.append((name, open(os.path.join(src, folder, name), "rb").read(), 0))

# OgXHD's wdb.dat: "'Game / ID: 4343000e" names the title, ":4343000e" starts
# it, then hex lines in pairs (find, replace); "'" lines are comments
game, title, lines = None, None, []
next_game = None  # the comment's name, for the title the next ":" starts
def wdb_flush():
    if title is not None and lines:
        if len(lines) % 2:
            sys.exit("wdb.dat: %08x has an odd number of lines" % title)
        # a pair whose lines differ in length, or with half a byte, is a
        # typo in the database (one in 272d76c): left out, with the rest kept
        pairs = [(a, b) for a, b in zip(lines[::2], lines[1::2])]
        good = [(a, b) for a, b in pairs if len(a) == len(b) and not len(a) % 2]
        if len(good) < len(pairs):
            print("wdb.dat: %08x: %d of %d pairs left out (lengths)" % (title, len(pairs) - len(good), len(pairs)))
        lines[:] = [x for p in good for x in p]
        if not lines:
            return
        name = (game or "%08X" % title).replace(": ", " - ").replace(":", " -").replace("/", "-")
        files.append(("%s (16-9 Widescreen, OgXHD).wdb" % name, ("\n".join(lines) + "\n").encode(), title))
for raw in open(os.path.join(src, "!OgXHD", "wdb.dat"), encoding="latin-1"):
    s = raw.strip()
    if not s:
        continue
    if s.startswith("'"):
        if " / ID: " in s:
            next_game = s[1:s.index(" / ID: ")].strip()
        continue
    if s.startswith(":"):
        wdb_flush()
        lines = []
        if s.lower() == ":end":
            title = None
            break
        title = int(s[1:], 16)
        game, next_game = next_game, None
        continue
    if any(c not in "0123456789abcdefABCDEF" for c in s):
        sys.exit("wdb.dat: not hex: %r" % s)
    lines.append(s)
wdb_flush()

out = ["/* Generated by scripts/gen_bundled_patches.py, do not edit.",
       " * The 16-9 Widescreen, 60 FPS and Miscellaneous patches of",
       " * https://github.com/icup321/XboxGraphicalPatches (commit %s), collected by" % commit,
       " * icup321 from their authors, and the 16:9 database of its OgXHD tool",
       " * (wdb.dat, one .wdb per title ID), bundled with permission (issue #16). */",
       "",
       "typedef struct {",
       "    const char *name;",
       "    const unsigned char *data;",
       "    unsigned int size;",
       "    /* a .wdb's title ID; the others go by their game's name */",
       "    unsigned int title_id;",
       "} LibretroBundledPatch;",
       ""]
for i, (name, data, title) in enumerate(files):
    out.append("static const unsigned char libretro_bundled_patch_%d[] = {" % i)
    for j in range(0, len(data), 16):
        out.append("    " + ", ".join("0x%02x" % b for b in data[j:j + 16]) + ",")
    out.append("};")
out.append("")
out.append("static const LibretroBundledPatch libretro_bundled_patches[] = {")
for i, (name, data, title) in enumerate(files):
    esc = name.replace("\\", "\\\\").replace('"', '\\"')
    out.append('    { "%s", libretro_bundled_patch_%d, %d, 0x%08x },' % (esc, i, len(data), title))
out.append("};")
open("ui/libretro-bundled-patches.h", "w", newline="\n").write("\n".join(out) + "\n")
print(len(files), "patches")
