#!/usr/bin/env python3
r"""Writes ui/libretro-hakux-mods.h: the 60 fps mods of hakuX
(https://github.com/rfandango/hakuX, mods/, GPL-3.0-or-later).

hakuX keeps one folder per disc release, <title ID>.<certificate version>,
and in it one folder per mod with a mod.txt: lines "0xADDRESS: bytes" or
"0xADDRESS: old -> new" under "[default.xbe]", addresses virtual as the XBE
is loaded (a "[$u\default.xbe]" section, for an Xbox Live title update, is
left to the update's XBE and skipped here). Each 60 fps mod becomes "<game> (60 fps, hakuX).hakux" with its
mod.txt as it is, listed for that title ID and version only (ui/libretro.c,
xbe_apply_hakux). The 120 fps ones need the console's vblank raised
("refresh:"), which the core has no way to do yet: left out.

    python3 scripts/gen_hakux_mods.py <hakuX checkout> [commit]
"""
import os
import sys

# The games' names, for the option labels (xdb's, as the box has them)
GAMES = {
    0x46530002: "Otogi - Myth of Demons",
    0x46530004: "Otogi 2 - Immortal Warriors",
    0x4D530004: "Halo - Combat Evolved",
    0x4D530021: "Crimson Skies - High Road to Revenge",
    0x4D53004B: "Project Gotham Racing 2",
    0x4D530051: "Conker - Live & Reloaded",
    0x4D530064: "Halo 2",
    0x4D53006E: "Forza Motorsport",
}
MODS = ["60fps"]
# Games whose 60 fps patch XboxGraphicalPatches already has (bundled, NNshi):
# Halo, Halo 2, Otogi, Crimson Skies, Conker
SKIP = {0x4D530004, 0x4D530064, 0x46530002, 0x4D530021, 0x4D530051}

src = os.path.join(sys.argv[1], "mods")
commit = sys.argv[2] if len(sys.argv) > 2 else "?"
files = []
for key in sorted(os.listdir(src)):
    if not os.path.isdir(os.path.join(src, key)) or "." not in key:
        continue
    tid, ver = key.split(".", 1)
    title, version = int(tid, 16), int(ver)
    if title in SKIP:
        continue
    for mod in MODS:
        path = os.path.join(src, key, mod, "mod.txt")
        if not os.path.exists(path):
            continue
        text = open(path, "rb").read()
        # its title update section ([$u\default.xbe]) is skipped by the core
        if b"\nrefresh:" in b"\n" + text:
            sys.exit("%s: refresh, not handled" % path)
        if os.path.isdir(os.path.join(src, key, mod, "files")):
            sys.exit("%s: replaces disc files, not handled" % path)
        game = GAMES.get(title, "%08X" % title)
        files.append(("%s (60 fps, hakuX).hakux" % game, text, title, version))

out = ["/* Generated by scripts/gen_hakux_mods.py, do not edit.",
       " * The 60 fps mods of https://github.com/rfandango/hakuX (commit %s)," % commit,
       " * mods/<title ID>.<version>/60fps/mod.txt, GPL-3.0-or-later. */",
       "",
       "typedef struct {",
       "    const char *name;",
       "    const unsigned char *data;",
       "    unsigned int size;",
       "    unsigned int title_id;",
       "    /* the XBE certificate's version: a mod's addresses hold for one release */",
       "    unsigned int version;",
       "} LibretroHakuXMod;",
       ""]
for i, (name, data, title, version) in enumerate(files):
    out.append("static const unsigned char libretro_hakux_mod_%d[] = {" % i)
    for j in range(0, len(data), 16):
        out.append("    " + ", ".join("0x%02x" % b for b in data[j:j + 16]) + ",")
    out.append("};")
out.append("")
out.append("static const LibretroHakuXMod libretro_hakux_mods[] = {")
for i, (name, data, title, version) in enumerate(files):
    esc = name.replace("\\", "\\\\").replace('"', '\\"')
    out.append('    { "%s", libretro_hakux_mod_%d, %d, 0x%08x, %d },' % (esc, i, len(data), title, version))
out.append("};")
open("ui/libretro-hakux-mods.h", "w", newline="\n").write("\n".join(out) + "\n")
print(len(files), "mods")
