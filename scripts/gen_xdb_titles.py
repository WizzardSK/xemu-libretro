#!/usr/bin/env python3
"""ui/libretro-xdb-titles.h: every title name in xemu-project/xdb with its
title IDs, by the Patch Manager's normalized name (ui/libretro.c,
patch_name_norm), so a patch named after its game finds the game's IDs.

    git clone --filter=blob:none --no-checkout https://github.com/xemu-project/xdb
    (cd xdb && git sparse-checkout set --no-cone '/titles/*/*/info.json' && git checkout)
    scripts/gen_xdb_titles.py xdb > ui/libretro-xdb-titles.h
"""
import glob, json, re, sys

# patch names (XboxGraphicalPatches) that differ from xdb's
ALIASES = {
    "Family Guy": "Family Guy: Video Game!",
    "Need for Speed - Most Wanted - Black Edition": "Need for Speed: Most Wanted",
    "Nickelodeon SpongeBob SquarePants - Battle for Bikini Bottom":
        "Nickelodeon SpongeBob SquarePants in: Battle for Bikini Bottom",
}
ROMAN = {"ii": "2", "iii": "3", "iv": "4", "vs": "versus"}


def norm(s):
    words = re.findall(r"[a-z0-9]+", s.lower().replace("&", " and "))
    return "".join(ROMAN.get(w, w) for w in words if w != "the")


def main(root):
    ids_by_name = {}
    for f in sorted(glob.glob(f"{root}/titles/*/*/info.json")):
        d = json.load(open(f, encoding="utf-8"))
        ids = {d.get("title_id", "")} | {r.get("title_id", "") for r in d.get("releases", [])}
        names = {d.get("name", "")} | {r.get("name", "") for r in d.get("releases", [])}
        for n in filter(None, names):
            ids_by_name.setdefault(n, set()).update(i.upper() for i in ids if i)
    entries = set()
    for n, ids in ids_by_name.items():
        for i in ids:
            entries.add((norm(n), int(i, 16)))
    for alias, n in ALIASES.items():
        for i in ids_by_name.get(n, ()):
            entries.add((norm(alias), int(i, 16)))
    print("/* Generated by scripts/gen_xdb_titles.py from xemu-project/xdb: every")
    print(" * title name, normalized as patch_name_norm does, with its title IDs */")
    print("#ifndef LIBRETRO_XDB_TITLES_H\n#define LIBRETRO_XDB_TITLES_H\n")
    print("#include <stdint.h>\n")
    print("static const struct { const char *name; uint32_t title_id; } libretro_xdb_titles[] = {")
    for n, i in sorted(entries):
        print(f'    {{"{n}", 0x{i:08X}}},')
    print("};\n\n#endif")


main(sys.argv[1])
